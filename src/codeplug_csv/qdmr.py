"""qDMR / dmrconf YAML codeplug writer.

qDMR (and its command line sibling ``dmrconf``) uses a single device
independent YAML codeplug.  There is no way to make dmrconf emit that YAML
from any other text format, so we generate it directly.

Schema notes (verified against upstream ``lib/config.cc``):

* Every element that is referenced elsewhere needs an explicit ``id``.
* References are by ``id``: zones list channel ids in ``A``, channels point at
  a contact id and a group list id.
* A DMR talkgroup is just a contact with ``type: GroupCall``.
* Unknown keys are silently ignored, so the writer validates its own links.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

import yaml

from .config import MAX_NAME_LENGTH
from .models import AnytoneChannel, AnytoneZone, TalkGroup
from .zones import drop_empty_zones

logger = logging.getLogger(__name__)

OUTPUT_FILENAME = "codeplug.yaml"

# dmrconf accepts both the current ``dmr``/``fm`` channel keys and the older
# ``digital``/``analog`` aliases (which emit a deprecation warning on 0.15+).
# The aliases are the only keys understood by every release from 0.9 to 0.15,
# so they are what we emit.  Flip this mapping to use the modern keys once the
# minimum supported dmrconf is known to be 0.15 or newer.
DIGITAL_KEY = "digital"
ANALOG_KEY = "analog"

# ``version`` is written by dmrconf but never enforced on read (no migration
# logic exists).  0.9.0 is the value upstream's own example file still uses and
# it loads in every current release.
QDMR_VERSION = "0.9.0"

POWER_ENUM: dict[str, str] = {
    "Turbo": "Max",
    "High": "High",
    "Mid": "Mid",
    "Low": "Low",
}

BANDWIDTH_ENUM: dict[str, str] = {"25K": "Wide", "12.5K": "Narrow"}

# AnyTone-style radios restrict channel/zone/contact names to 16 characters,
# and radio ID names to 8.
MAX_RADIO_ID_NAME = 8

# TG9 "Local" is the default contact for every DMR channel.
DEFAULT_TALKGROUP_NUMBER = 9
DEFAULT_TALKGROUP_NAME = "Local"

# Placeholder identity, used when the operator does not pass --dmr-id.
PLACEHOLDER_DMR_ID = 0
PLACEHOLDER_CALLSIGN = "NOCALL"

# d878uv allows up to 250 group lists of 64 contacts each; we emit one list
# holding every group call so any channel can receive any UK talkgroup.
GROUP_LIST_ID = "grp_uk"
GROUP_LIST_NAME = "UK ALL"
GROUP_LIST_MAX_CONTACTS = 64

RADIO_ID_ID = "radioid1"

HEADER = """\
# qDMR / dmrconf codeplug generated by codeplug-csv.
# Open in the qDMR GUI, or write it to a radio with:
#   dmrconf write --radio=<radio> codeplug.yaml
# Validate without hardware with:
#   dmrconf verify --radio=<radio> codeplug.yaml
"""

DMR_ID_PLACEHOLDER_NOTE = """\
# NOTE: this file uses the placeholder radio identity number 0 / callsign
# NOCALL.  Set your own DMR ID before programming a radio, either by editing
# radioIDs below or by re-running with --dmr-id <id> --callsign <call>.
"""


def _mhz(value: str) -> float:
    """Convert the model's MHz string to a float for YAML."""
    return float(value)


def _tone(value: str) -> dict[str, float] | None:
    """Convert an Anytone tone string to a qDMR tone mapping."""
    if not value or value == "Off":
        return None
    try:
        return {"ctcss": float(value)}
    except ValueError:
        logger.warning("Cannot express tone %r in qDMR output; omitted", value)
        return None


def _power(value: str) -> str:
    """Map an Anytone power label onto the qDMR power enum."""
    try:
        return POWER_ENUM[value]
    except KeyError:
        logger.warning("Unknown power %r, using High", value)
        return "High"


def _bandwidth(value: str) -> str:
    """Map an Anytone bandwidth label onto the qDMR bandwidth enum."""
    return BANDWIDTH_ENUM.get(value, "Narrow")


def _color_code(value: int) -> int:
    """Clamp the colour code to the 0-15 range dmrconf actually accepts."""
    if 0 <= value <= 15:
        return value
    clamped = min(max(value, 0), 15)
    logger.warning("Colour code %d out of range, clamped to %d", value, clamped)
    return clamped


def _contact_id(number: int) -> str:
    return f"tg{number}"


def _build_contacts(talkgroups: list[TalkGroup]) -> list[dict[str, Any]]:
    """Build the ``contacts`` list, deduplicated by DMR ID.

    TG9 is always present because every DMR channel defaults to it, even if
    the BrandMeister fetch did not return it.
    """
    by_number: dict[int, TalkGroup] = {}
    for tg in talkgroups:
        by_number.setdefault(tg.radio_id, tg)

    if DEFAULT_TALKGROUP_NUMBER not in by_number:
        by_number[DEFAULT_TALKGROUP_NUMBER] = TalkGroup(
            name=DEFAULT_TALKGROUP_NAME,
            radio_id=DEFAULT_TALKGROUP_NUMBER,
        )

    contacts = []
    for number in sorted(by_number):
        tg = by_number[number]
        contacts.append(
            {
                "dmr": {
                    "id": _contact_id(number),
                    "name": tg.name,
                    "type": (
                        "PrivateCall" if tg.call_type == "Private Call"
                        else "GroupCall"
                    ),
                    "number": number,
                }
            }
        )
    return contacts


def _build_group_list(contacts: list[dict[str, Any]]) -> dict[str, Any]:
    """Build the single RX group list from the group call contacts.

    Private calls are excluded: radios do not support them in group lists and
    dmrconf drops them without saying so.
    """
    members = [
        contact["dmr"]["id"]
        for contact in contacts
        if contact["dmr"]["type"] == "GroupCall"
    ]
    if len(members) > GROUP_LIST_MAX_CONTACTS:
        logger.warning(
            "Group list has %d contacts, above the %d the radios support",
            len(members),
            GROUP_LIST_MAX_CONTACTS,
        )
    return {"id": GROUP_LIST_ID, "name": GROUP_LIST_NAME, "contacts": members}


def _channel_body(
    channel: AnytoneChannel,
    channel_id: str,
    contact_by_name: dict[str, str],
) -> dict[str, Any]:
    """Build the type-specific body of a single channel entry."""
    body: dict[str, Any] = {
        "id": channel_id,
        "name": channel.name,
        "rxFrequency": _mhz(channel.rx_freq),
        "txFrequency": _mhz(channel.tx_freq),
    }

    if channel.channel_type == "D-Digital":
        key = DIGITAL_KEY
        wanted = channel.contact or DEFAULT_TALKGROUP_NAME
        contact = contact_by_name.get(wanted)
        if contact is None:
            logger.warning(
                "Channel %r references unknown talkgroup %r, using TG%d",
                channel.name,
                wanted,
                DEFAULT_TALKGROUP_NUMBER,
            )
            contact = contact_by_name[DEFAULT_TALKGROUP_NAME]
        body.update(
            {
                "admit": (
                    "ColorCode"
                    if channel.rpt_type in ("RPT", "GW")
                    else "Always"
                ),
                "colorCode": _color_code(channel.color_code),
                "timeSlot": f"TS{channel.slot}",
                "contact": contact,
                "groupList": GROUP_LIST_ID,
            }
        )
    else:
        key = ANALOG_KEY
        body.update({"bandwidth": _bandwidth(channel.bandwidth), "admit": "Always"})
        rx_tone = _tone(channel.ctcss_decode)
        tx_tone = _tone(channel.ctcss_encode)
        if rx_tone:
            body["rxTone"] = rx_tone
        if tx_tone:
            body["txTone"] = tx_tone

    body["power"] = _power(channel.power)

    # "PTT Prohibit" channels (PMR446, marine VHF) are receive only.
    if channel.tx_prohibit == "On":
        body["rxOnly"] = True

    return {key: body}


def _normalise_callsign(callsign: str) -> str:
    """Upper-case and fit a callsign into the radio's 8 character field."""
    text = callsign.strip().upper() or PLACEHOLDER_CALLSIGN
    if len(text) > MAX_RADIO_ID_NAME:
        logger.warning(
            "Callsign %r truncated to %d characters", text, MAX_RADIO_ID_NAME
        )
        text = text[:MAX_RADIO_ID_NAME]
    return text


def _check_links(codeplug: dict[str, Any]) -> None:
    """Fail loudly on dangling references, which dmrconf would reject.

    Unknown keys are ignored by dmrconf, so the writer has to be its own
    schema guard for everything that can be checked locally.
    """
    contact_ids = {contact["dmr"]["id"] for contact in codeplug["contacts"]}
    group_ids = {group["id"] for group in codeplug["groupLists"]}
    channel_ids = [
        next(iter(entry.values()))["id"] for entry in codeplug["channels"]
    ]
    if len(set(channel_ids)) != len(channel_ids):
        raise ValueError("Duplicate qDMR channel ids")

    known = set(channel_ids)
    for entry in codeplug["channels"]:
        body = next(iter(entry.values()))
        if body["name"] and len(body["name"]) > MAX_NAME_LENGTH:
            raise ValueError(
                f"Channel name {body['name']!r} exceeds {MAX_NAME_LENGTH} characters"
            )
        contact = body.get("contact")
        if contact is not None and contact not in contact_ids:
            raise ValueError(f"Dangling contact reference {contact!r}")
        group = body.get("groupList")
        if group is not None and group not in group_ids:
            raise ValueError(f"Dangling group list reference {group!r}")

    members: list[str] = []
    for zone in codeplug["zones"]:
        if len(zone["name"]) > MAX_NAME_LENGTH:
            raise ValueError(
                f"Zone name {zone['name']!r} exceeds {MAX_NAME_LENGTH} characters"
            )
        for member in zone["A"]:
            if member not in known:
                raise ValueError(f"Dangling channel reference {member!r}")
        members.extend(zone["A"])

    if sorted(members) != sorted(channel_ids):
        raise ValueError(
            "Every channel must belong to exactly one zone "
            f"(zones cover {len(members)} of {len(channel_ids)} channels)"
        )


def build_codeplug(
    channels: list[AnytoneChannel],
    zones: list[AnytoneZone],
    talkgroups: list[TalkGroup],
    *,
    dmr_id: int = PLACEHOLDER_DMR_ID,
    callsign: str = PLACEHOLDER_CALLSIGN,
) -> dict[str, Any]:
    """Assemble a device independent qDMR codeplug as a plain dict."""
    zones = drop_empty_zones(zones)
    names = [channel.name for channel in channels]
    if len(set(names)) != len(names):
        duplicates = sorted({name for name in names if names.count(name) > 1})
        raise ValueError(f"Duplicate channel names: {duplicates}")

    channel_ids = {
        name: f"ch{index}" for index, name in enumerate(names, start=1)
    }

    contacts = _build_contacts(talkgroups)
    contact_by_name = {
        contact["dmr"]["name"]: contact["dmr"]["id"] for contact in contacts
    }
    group_list = _build_group_list(contacts)

    codeplug: dict[str, Any] = {
        "version": QDMR_VERSION,
        "settings": {"defaultID": RADIO_ID_ID},
        "radioIDs": [
            {
                "dmr": {
                    "id": RADIO_ID_ID,
                    "name": _normalise_callsign(callsign),
                    "number": dmr_id,
                }
            }
        ],
        "contacts": contacts,
        "groupLists": [group_list],
        "channels": [
            _channel_body(channel, channel_ids[channel.name], contact_by_name)
            for channel in channels
        ],
        "zones": [
            {
                "id": f"z{index}",
                "name": zone.name,
                "A": [channel_ids[channel.name] for channel in zone.channels],
            }
            for index, zone in enumerate(zones, start=1)
        ],
    }

    _check_links(codeplug)
    return codeplug


def write_qdmr(
    channels: list[AnytoneChannel],
    zones: list[AnytoneZone],
    talkgroups: list[TalkGroup],
    output_dir: Path,
    *,
    dmr_id: int = PLACEHOLDER_DMR_ID,
    callsign: str = PLACEHOLDER_CALLSIGN,
) -> Path:
    """Write ``codeplug.yaml`` for qDMR / dmrconf."""
    codeplug = build_codeplug(
        channels, zones, talkgroups, dmr_id=dmr_id, callsign=callsign
    )

    if dmr_id == PLACEHOLDER_DMR_ID:
        logger.warning(
            "Using the placeholder DMR ID %d; pass --dmr-id to set your own",
            dmr_id,
        )

    path = output_dir / OUTPUT_FILENAME
    try:
        path.write_text(
            HEADER
            + (DMR_ID_PLACEHOLDER_NOTE if dmr_id == PLACEHOLDER_DMR_ID else "")
            + yaml.safe_dump(
                codeplug,
                sort_keys=False,
                allow_unicode=True,
                default_flow_style=False,
                width=1000,
            ),
            encoding="utf-8",
        )
    except OSError as exc:
        logger.error("Failed to write %s: %s", path, exc)
        raise

    logger.info("Wrote qDMR codeplug to %s", path)
    return path
